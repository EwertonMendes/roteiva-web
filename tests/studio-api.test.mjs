import assert from 'node:assert/strict';
const base='http://127.0.0.1:5174';
const owner=`roteiva_qa_${Date.now()}`;
const auth={'oai-authenticated-user-id':owner,'oai-authenticated-user-email':'qa@example.test'};
async function request(path,options={},identity=auth){const r=await fetch(base+path,{...options,headers:{...identity,...options.headers}});const contentType=r.headers.get('content-type')||'';return {status:r.status,data:contentType.includes('json')?await r.json():await r.text(),headers:r.headers};}
const empty={projects:[],clients:[],financeEntries:[],calendarEvents:[],libraryAssets:[]};
assert.equal((await request('/api/workspace',{},{})).status,401);
assert.deepEqual((await request('/api/workspace')).data,{workspace:null,revision:0});
const save=(workspace,revision)=>request('/api/workspace',{method:'PUT',headers:{'Content-Type':'application/json'},body:JSON.stringify({workspace,revision})});
assert.equal((await save(empty,0)).status,200);
assert.equal((await save(empty,0)).status,409);
assert.equal((await save({...empty,financeEntries:[{id:1,project:'Teste',client:'Teste',date:'16/10/2026',amount:-1,status:'Recebido'}]},1)).status,400);
const bytes=new Uint8Array([0,0,0,24,102,116,121,112,109,112,52,50]);
const media=await request('/api/media',{method:'POST',body:bytes,headers:{'Content-Type':'video/mp4','X-File-Name':'qa.mp4','X-File-Size':String(bytes.length)}});assert.equal(media.status,200);assert.ok(media.data.key.startsWith(`studio/${owner}/`));
const asset={id:123,name:'qa.mp4',kind:'Vídeo',size:'0.01 MB',addedAt:'16/10/2026',project:'Teste',color:'violet',fileKey:media.data.key,url:media.data.url,mimeType:'video/mp4'};
assert.equal((await save({...empty,libraryAssets:[asset]},1)).status,200);
assert.equal((await request(media.data.url,{},{})).status,401);
assert.equal((await request(media.data.url,{}, {...auth,'oai-authenticated-user-id':'another_qa_user'})).status,404);
assert.equal((await request(media.data.url)).status,200);
const ranged=await request(media.data.url,{headers:{Range:'bytes=0-3'}});assert.equal(ranged.status,206);assert.equal(ranged.headers.get('Content-Range'),'bytes 0-3/12');
