import assert from 'node:assert/strict';
import {parseMoney, splitInstallments, sumMoney, toISO} from '../src/studio-finance.ts';
assert.equal(parseMoney('1.234,56'),1234.56);
assert.equal(parseMoney('1234.56'),1234.56);
assert.ok(Number.isNaN(parseMoney('inválido')));
assert.equal(sumMoney([{amount:0.1},{amount:0.2}]),0.3);
const parts=splitInstallments(100,3,new Date(2026,0,31,12));
assert.deepEqual(parts.map(p=>p.amount),[33.34,33.33,33.33]);
assert.deepEqual(parts.map(p=>p.date),['31/01/2026','28/02/2026','31/03/2026']);
assert.equal(sumMoney(parts),100);
assert.deepEqual(splitInstallments(1,2,new Date(2026,11,31,12)).map(p=>p.date),['31/12/2026','31/01/2027']);
assert.equal(splitInstallments(2,2,new Date(2028,0,31,12))[1].date,'29/02/2028');
assert.throws(()=>splitInstallments(.01,2,new Date()));
assert.throws(()=>splitInstallments(5,0,new Date()));
assert.equal(toISO('31/12/2026'),'2026-12-31');
console.log('Financeiro: centavos, parcelas, fevereiro, ano bissexto e virada de ano OK');
